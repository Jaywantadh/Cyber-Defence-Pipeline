"""LLM Prompt and Output Guardrails Module.

Provides defensive checks for LLM-assisted incident reasoning:
1. sanitize_for_prompt: Sanitizes untrusted text (e.g. process names, telemetry fields,
   gate reasons) before interpolation into LLM prompts to prevent prompt injection.
2. check_groundedness: Inspects generated LLM explanations for ungrounded numbers or
   unverified IP address claims not present in the incident evidence.
"""

from pathlib import Path
import re
import sys
from typing import Any, Dict, List, Optional, Union

