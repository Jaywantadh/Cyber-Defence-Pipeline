def generate_host_events(
    n_events: int = 50000,
    attack_ratio: float = 0.03,
    random_state: int = 42,
) -> pd.DataFrame:
    """Generates synthetic Windows host process events with controlled feature overlap.

    [SYNTHETIC DATA SOURCE NOTICE]
    All generated events are simulated for prototype testing and pipeline
    validation. They do NOT represent real endpoint telemetry.

    Controlled overlap:
    - ~15% of BENIGN rows use attack-associated process/parent pairs to simulate
      benign administrative macros or scripts (surface false positives).
    - ~10% of malicious rows vary the parent process to adjacent benign-associated
      parents (e.g. powershell.exe spawned by outlook.exe).

    Parameters
    ----------
    n_events : int, default=50000
        Total number of synthetic events to generate.
    attack_ratio : float, default=0.03
        Proportion of malicious events in the generated dataset.
    random_state : int, default=42
        Random seed for full reproducibility.

    Returns
    -------
    pandas.DataFrame
        DataFrame containing synthetic Windows host events with columns:
        - event_id (sequential int)
        - timestamp (sequential, spaced over a simulated 24h period)
        - computer (fake computer hostname from pool of 50)
        - user (fake username from pool of 30)
        - process_name (common benign or synthetic attack process)
        - parent_process (plausible parent process)
        - is_malicious (0 for benign, 1 for malicious)
        - label ("BENIGN", "SUSPICIOUS_PROCESS_INJECTION", or
          "PRIVILEGE_ESCALATION_ATTEMPT")
    """
    rng = np.random.default_rng(random_state)

    # 1. Sequential event IDs (1 to n_events)
    event_ids = np.arange(1, n_events + 1, dtype=int)

    # 2. Sequential timestamps spaced realistically over a simulated 24-hour period
    base_time = pd.Timestamp("2025-01-15 00:00:00")
    second_offsets = np.sort(rng.uniform(0, 86400, size=n_events))
    timestamps = (base_time + pd.to_timedelta(second_offsets, unit="s")).strftime("%Y-%m-%d %H:%M:%S")

    # 3. Randomly chosen computers and users from fake pools
    computers = rng.choice(FAKE_COMPUTERS, size=n_events)
    users = rng.choice(FAKE_USERS, size=n_events)

    # 4. Partition malicious vs benign counts
    n_malicious = int(round(n_events * attack_ratio))
    n_benign = n_events - n_malicious

    n_injection = n_malicious // 2
    n_priv_esc = n_malicious - n_injection

    # 5. Initialize labels and malicious flags
    labels = np.array(["BENIGN"] * n_events, dtype=object)
    is_malicious = np.zeros(n_events, dtype=int)

    # Select random indices across the timeline for malicious events
    if n_malicious > 0:
        malicious_indices = rng.choice(n_events, size=n_malicious, replace=False)
        rng.shuffle(malicious_indices)
        injection_indices = malicious_indices[:n_injection]
        priv_esc_indices = malicious_indices[n_injection:]

        labels[injection_indices] = "SUSPICIOUS_PROCESS_INJECTION"
        labels[priv_esc_indices] = "PRIVILEGE_ESCALATION_ATTEMPT"
        is_malicious[malicious_indices] = 1

    # 6. Assign parent_process and process_name with controlled overlap
    parent_processes = np.empty(n_events, dtype=object)
    process_names = np.empty(n_events, dtype=object)

    # 6a. Benign rows: ~15% overlap with attack-associated process pairs
    benign_indices = np.where(is_malicious == 0)[0]
    n_benign_overlap = int(round(n_benign * 0.15))
    n_benign_normal = n_benign - n_benign_overlap

    benign_overlap_indices = rng.choice(benign_indices, size=n_benign_overlap, replace=False)
    benign_normal_indices = np.setdiff1d(benign_indices, benign_overlap_indices)

    if n_benign_normal > 0:
        benign_choices = rng.integers(0, len(BENIGN_PROCESS_PAIRS), size=n_benign_normal)
        parent_processes[benign_normal_indices] = [BENIGN_PROCESS_PAIRS[i][0] for i in benign_choices]
        process_names[benign_normal_indices] = [BENIGN_PROCESS_PAIRS[i][1] for i in benign_choices]

    if n_benign_overlap > 0:
        overlap_choices = rng.integers(0, len(ATTACK_PROCESS_PAIRS), size=n_benign_overlap)
        parent_processes[benign_overlap_indices] = [ATTACK_PROCESS_PAIRS[i][0] for i in overlap_choices]
        process_names[benign_overlap_indices] = [ATTACK_PROCESS_PAIRS[i][1] for i in overlap_choices]

    # 6b. Malicious rows: ~10% vary parent process to adjacent benign-associated parents
    if n_injection > 0:
        n_inj_varied = int(round(n_injection * 0.10))
        n_inj_fixed = n_injection - n_inj_varied

        inj_varied_indices = rng.choice(injection_indices, size=n_inj_varied, replace=False)
        inj_fixed_indices = np.setdiff1d(injection_indices, inj_varied_indices)

        if n_inj_fixed > 0:
            inj_fix_choices = rng.integers(0, len(INJECTION_PROCESS_PAIRS), size=n_inj_fixed)
            parent_processes[inj_fixed_indices] = [INJECTION_PROCESS_PAIRS[i][0] for i in inj_fix_choices]
            process_names[inj_fixed_indices] = [INJECTION_PROCESS_PAIRS[i][1] for i in inj_fix_choices]

        if n_inj_varied > 0:
            inj_var_choices = rng.integers(0, len(INJECTION_VARIED_PAIRS), size=n_inj_varied)
            parent_processes[inj_varied_indices] = [INJECTION_VARIED_PAIRS[i][0] for i in inj_var_choices]
            process_names[inj_varied_indices] = [INJECTION_VARIED_PAIRS[i][1] for i in inj_var_choices]

    if n_priv_esc > 0:
        n_pe_varied = int(round(n_priv_esc * 0.10))
        n_pe_fixed = n_priv_esc - n_pe_varied

        pe_varied_indices = rng.choice(priv_esc_indices, size=n_pe_varied, replace=False)
        pe_fixed_indices = np.setdiff1d(priv_esc_indices, pe_varied_indices)

        if n_pe_fixed > 0:
            pe_fix_choices = rng.integers(0, len(PRIV_ESC_PROCESS_PAIRS), size=n_pe_fixed)
            parent_processes[pe_fixed_indices] = [PRIV_ESC_PROCESS_PAIRS[i][0] for i in pe_fix_choices]
            process_names[pe_fixed_indices] = [PRIV_ESC_PROCESS_PAIRS[i][1] for i in pe_fix_choices]

        if n_pe_varied > 0:
            pe_var_choices = rng.integers(0, len(PRIV_ESC_VARIED_PAIRS), size=n_pe_varied)
            parent_processes[pe_varied_indices] = [PRIV_ESC_VARIED_PAIRS[i][0] for i in pe_var_choices]
            process_names[pe_varied_indices] = [PRIV_ESC_VARIED_PAIRS[i][1] for i in pe_var_choices]

    # 7. Construct DataFrame
    df = pd.DataFrame(
        {
            "event_id": event_ids,
            "timestamp": timestamps,
            "computer": computers,
            "user": users,
            "process_name": process_names,
            "parent_process": parent_processes,
            "is_malicious": is_malicious,
            "label": labels,
        }
    )

    return df


def load_synthetic_host_events(path: Union[str, Path] = None) -> pd.DataFrame:
    """Loads synthetic host telemetry events from CSV, safely ignoring comment headers.

    [SYNTHETIC DATA SOURCE NOTICE]
    Loads simulated endpoint data generated for prototyping and testing.

    Parameters
    ----------
    path : str or pathlib.Path, optional
        Path to synthetic host CSV. Defaults to data/raw/synthetic_host_events.csv.

    Returns
    -------
    pandas.DataFrame
        Loaded synthetic DataFrame with sanitized column headers.
    """
    if path is None:
        path = PROJECT_ROOT / "data" / "raw" / "synthetic_host_events.csv"
    path_str = str(path)
    df = pd.read_csv(path_str, comment="#")
    df.columns = df.columns.str.strip()
    return df


