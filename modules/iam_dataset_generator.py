"""Synthetic IAM Telemetry Dataset Generator.

[SYNTHETIC DATA SOURCE NOTICE]
==============================
WARNING: ALL DATA GENERATED BY THIS MODULE IS SYNTHETIC.
This module generates simulated Identity and Access Management (IAM) authentication
and logon telemetry for prototype testing, pipeline evaluation, and integration
demonstrations. It does NOT represent authentic enterprise Active Directory,
Okta, or Kerberos/NTLM authentication logs. All source/target hostnames, usernames,
logon types, and attack labels are synthetically synthesized.

Controlled feature overlap emerges naturally from realistic class-conditional
probability distributions rather than fixed lookup tables:
- BENIGN: ~95% SUCCESS, balanced Kerberos/NTLM, mostly Interactive/Network
- BRUTE_FORCE_LOGIN: ~90% FAILURE, primarily Network logon, mostly NTLM
- PASS_THE_HASH: ~85% SUCCESS, Network/RemoteInteractive logon, targeted NTLM

Real network flow data in this project is sourced separately from the CICIDS2017
dataset (see README.md).
"""

