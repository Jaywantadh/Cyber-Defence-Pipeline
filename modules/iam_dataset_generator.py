# Supported discrete authentication attributes
AUTH_TYPES: List[str] = ["Kerberos", "NTLM", "Negotiate"]
LOGON_TYPES: List[str] = [
    "Interactive",
    "Network",
    "Service",
    "Batch",
    "RemoteInteractive",
]
AUTH_RESULTS: List[str] = ["SUCCESS", "FAILURE"]


def generate_iam_events(
    n_events: int = 50000,
    attack_ratio: float = 0.03,
    random_state: int = 42,
) -> pd.DataFrame:
    """Generates synthetic Windows IAM authentication and logon events using probabilistic distributions.

    [SYNTHETIC DATA SOURCE NOTICE]
    All generated events are simulated for prototype testing and pipeline
    validation. They do NOT represent real IAM telemetry.

    Parameters
    ----------
    n_events : int, default=50000
        Total number of synthetic events to generate.
    attack_ratio : float, default=0.03
        Proportion of malicious events in the generated dataset.
    random_state : int, default=42
        Random seed for full reproducibility.

    Returns
    -------
    pandas.DataFrame
        DataFrame containing synthetic Windows IAM events with columns:
        - event_id (sequential int)
        - timestamp (sequential, spaced over a simulated 24h period)
        - source_computer (fake computer hostname from pool of 50)
        - target_computer (fake computer hostname from pool of 50)
        - user (fake username from pool of 30)
        - auth_type ("Kerberos", "NTLM", or "Negotiate")
        - logon_type ("Interactive", "Network", "Service", "Batch", or "RemoteInteractive")
        - auth_result ("SUCCESS" or "FAILURE")
        - is_malicious (0 for benign, 1 for malicious)
        - label ("BENIGN", "BRUTE_FORCE_LOGIN", or "PASS_THE_HASH")
    """
    rng = np.random.default_rng(random_state)

    # 1. Sequential event IDs (1 to n_events)
    event_ids = np.arange(1, n_events + 1, dtype=int)

    # 2. Sequential timestamps spaced realistically over a simulated 24-hour period
    base_time = pd.Timestamp("2025-01-15 00:00:00")
    second_offsets = np.sort(rng.uniform(0, 86400, size=n_events))
    timestamps = (base_time + pd.to_timedelta(second_offsets, unit="s")).strftime("%Y-%m-%d %H:%M:%S")

    # 3. Randomly chosen identity endpoints from fake pools (excluded from model features)
    source_computers = rng.choice(FAKE_COMPUTERS, size=n_events)
    target_computers = rng.choice(FAKE_COMPUTERS, size=n_events)
    users = rng.choice(FAKE_USERS, size=n_events)

    # 4. Partition malicious vs benign counts
    n_malicious = int(round(n_events * attack_ratio))
    n_benign = n_events - n_malicious

    n_brute = n_malicious // 2
    n_pth = n_malicious - n_brute

    # 5. Initialize labels and malicious flags
    labels = np.array(["BENIGN"] * n_events, dtype=object)
    is_malicious = np.zeros(n_events, dtype=int)

    if n_malicious > 0:
        malicious_indices = rng.choice(n_events, size=n_malicious, replace=False)
        rng.shuffle(malicious_indices)
        brute_indices = malicious_indices[:n_brute]
        pth_indices = malicious_indices[n_brute:]

        labels[brute_indices] = "BRUTE_FORCE_LOGIN"
        labels[pth_indices] = "PASS_THE_HASH"
        is_malicious[malicious_indices] = 1

    # 6. Sample features from class-conditional distributions
    auth_types = np.empty(n_events, dtype=object)
    logon_types = np.empty(n_events, dtype=object)
    auth_results = np.empty(n_events, dtype=object)

    # 6a. BENIGN class distributions:
    # - auth_result: SUCCESS ~95%, FAILURE ~5%
    # - logon_type: mostly Interactive (45%) / Network (45%)
    # - auth_type: balanced Kerberos (48%) / NTLM (48%), rare Negotiate (4%)
    benign_mask = is_malicious == 0
    if n_benign > 0:
        auth_results[benign_mask] = rng.choice(AUTH_RESULTS, size=n_benign, p=[0.95, 0.05])
        logon_types[benign_mask] = rng.choice(
            LOGON_TYPES, size=n_benign, p=[0.45, 0.45, 0.04, 0.03, 0.03]
        )
        auth_types[benign_mask] = rng.choice(AUTH_TYPES, size=n_benign, p=[0.48, 0.48, 0.04])

    # 6b. BRUTE_FORCE_LOGIN class distributions:
    # - auth_result: FAILURE ~90%, SUCCESS ~10% (occasional lucky guess)
    # - logon_type: Network the vast majority of the time (92%)
    # - auth_type: NTLM most of the time (85%)
    if n_brute > 0:
        auth_results[brute_indices] = rng.choice(AUTH_RESULTS, size=n_brute, p=[0.10, 0.90])
        logon_types[brute_indices] = rng.choice(
            LOGON_TYPES, size=n_brute, p=[0.02, 0.92, 0.01, 0.01, 0.04]
        )
        auth_types[brute_indices] = rng.choice(AUTH_TYPES, size=n_brute, p=[0.10, 0.85, 0.05])

    # 6c. PASS_THE_HASH class distributions:
    # - auth_result: SUCCESS ~85%, FAILURE ~15% (attack succeeds by design)
    # - logon_type: Network (55%) or RemoteInteractive (41%)
    # - auth_type: NTLM specifically (98%)
    if n_pth > 0:
        auth_results[pth_indices] = rng.choice(AUTH_RESULTS, size=n_pth, p=[0.85, 0.15])
        logon_types[pth_indices] = rng.choice(
            LOGON_TYPES, size=n_pth, p=[0.02, 0.55, 0.01, 0.01, 0.41]
        )
        auth_types[pth_indices] = rng.choice(AUTH_TYPES, size=n_pth, p=[0.01, 0.98, 0.01])

    # 7. Construct DataFrame
    df = pd.DataFrame(
        {
            "event_id": event_ids,
            "timestamp": timestamps,
            "source_computer": source_computers,
            "target_computer": target_computers,
            "user": users,
            "auth_type": auth_types,
            "logon_type": logon_types,
            "auth_result": auth_results,
            "is_malicious": is_malicious,
            "label": labels,
        }
    )

    return df


def load_synthetic_iam_events(path: Union[str, Path] = None) -> pd.DataFrame:
    """Loads synthetic IAM telemetry events from CSV, safely ignoring comment headers.

    [SYNTHETIC DATA SOURCE NOTICE]
    Loads simulated identity/logon data generated for prototyping and testing.

    Parameters
    ----------
    path : str or pathlib.Path, optional
        Path to synthetic IAM CSV. Defaults to data/raw/synthetic_iam_events.csv.

    Returns
    -------
    pandas.DataFrame
        Loaded synthetic DataFrame with sanitized column headers.
    """
    if path is None:
        path = PROJECT_ROOT / "data" / "raw" / "synthetic_iam_events.csv"
    path_str = str(path)
    df = pd.read_csv(path_str, comment="#")
    df.columns = df.columns.str.strip()
    return df


