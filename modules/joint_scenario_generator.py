from modules.host_dataset_generator import (
    ATTACK_PROCESS_PAIRS,
    BENIGN_PROCESS_PAIRS,
    FAKE_USERS,
    INJECTION_PROCESS_PAIRS,
    INJECTION_VARIED_PAIRS,
    PRIV_ESC_PROCESS_PAIRS,
    PRIV_ESC_VARIED_PAIRS,
)
from modules.iam_dataset_generator import (
    AUTH_RESULTS,
    AUTH_TYPES,
    LOGON_TYPES,
)

# Constrained pool of 20 fake computers to ensure realistic cross-scenario entity overlap
SCENARIO_COMPUTERS: List[str] = [f"PC-{i:04d}" for i in range(1, 21)]

# Scenario combination categories
SCENARIO_TYPES: List[str] = [
    "BOTH_BENIGN",
    "HOST_ATTACK_ONLY",
    "IAM_ATTACK_ONLY",
    "BOTH_ATTACK",
]


def _generate_host_event(
    event_id: int,
    computer: str,
    user: str,
    timestamp: str,
    is_attack: bool,
    rng: np.random.Generator,
) -> Dict[str, Any]:
    """Generates a single synthetic host event adhering to host_dataset_generator schema."""
    if not is_attack:
        # Benign: ~15% controlled overlap with attack-associated pairs
        if rng.random() < 0.15:
            pair = ATTACK_PROCESS_PAIRS[rng.integers(0, len(ATTACK_PROCESS_PAIRS))]
        else:
            pair = BENIGN_PROCESS_PAIRS[rng.integers(0, len(BENIGN_PROCESS_PAIRS))]

        return {
            "event_id": event_id,
            "timestamp": timestamp,
            "computer": computer,
            "user": user,
            "process_name": pair[1],
            "parent_process": pair[0],
            "is_malicious": 0,
            "label": "BENIGN",
        }
    else:
        # Attack: 50% Injection, 50% Privilege Escalation
        if rng.random() < 0.5:
            label = "SUSPICIOUS_PROCESS_INJECTION"
            if rng.random() < 0.10:
                pair = INJECTION_VARIED_PAIRS[rng.integers(0, len(INJECTION_VARIED_PAIRS))]
            else:
                pair = INJECTION_PROCESS_PAIRS[rng.integers(0, len(INJECTION_PROCESS_PAIRS))]
        else:
            label = "PRIVILEGE_ESCALATION_ATTEMPT"
            if rng.random() < 0.10:
                pair = PRIV_ESC_VARIED_PAIRS[rng.integers(0, len(PRIV_ESC_VARIED_PAIRS))]
            else:
                pair = PRIV_ESC_PROCESS_PAIRS[rng.integers(0, len(PRIV_ESC_PROCESS_PAIRS))]

        return {
            "event_id": event_id,
            "timestamp": timestamp,
            "computer": computer,
            "user": user,
            "process_name": pair[1],
            "parent_process": pair[0],
            "is_malicious": 1,
            "label": label,
        }


def _generate_iam_event(
    event_id: int,
    target_computer: str,
    source_computer: str,
    user: str,
    timestamp: str,
    is_attack: bool,
    rng: np.random.Generator,
) -> Dict[str, Any]:
    """Generates a single synthetic IAM event adhering to iam_dataset_generator schema."""
    if not is_attack:
        # Benign distributions
        auth_result = rng.choice(AUTH_RESULTS, p=[0.95, 0.05])
        logon_type = rng.choice(LOGON_TYPES, p=[0.45, 0.45, 0.04, 0.03, 0.03])
        auth_type = rng.choice(AUTH_TYPES, p=[0.48, 0.48, 0.04])
        label = "BENIGN"
        is_malicious = 0
    else:
        # Attack: 50% Brute Force, 50% Pass-the-Hash
        is_malicious = 1
        if rng.random() < 0.5:
            label = "BRUTE_FORCE_LOGIN"
            auth_result = rng.choice(AUTH_RESULTS, p=[0.10, 0.90])
            logon_type = rng.choice(LOGON_TYPES, p=[0.02, 0.92, 0.01, 0.01, 0.04])
            auth_type = rng.choice(AUTH_TYPES, p=[0.10, 0.85, 0.05])
        else:
            label = "PASS_THE_HASH"
            auth_result = rng.choice(AUTH_RESULTS, p=[0.85, 0.15])
            logon_type = rng.choice(LOGON_TYPES, p=[0.02, 0.55, 0.01, 0.01, 0.41])
            auth_type = rng.choice(AUTH_TYPES, p=[0.01, 0.98, 0.01])

    return {
        "event_id": event_id,
        "timestamp": timestamp,
        "source_computer": source_computer,
        "target_computer": target_computer,
        "user": user,
        "auth_type": str(auth_type),
        "logon_type": str(logon_type),
        "auth_result": str(auth_result),
        "is_malicious": is_malicious,
        "label": label,
    }


def generate_joint_scenarios(
    n_scenarios: int = 200,
    random_state: int = 42,
) -> List[Dict[str, Any]]:
    """Generates paired Host and IAM test scenarios sharing a common target computer.

    [SYNTHETIC TEST HARNESS NOTICE]
    All scenarios are synthetically constructed to benchmark multi-agent correlation
    and conflict resolution. They do NOT represent real endpoint telemetry.

    Parameters
    ----------
    n_scenarios : int, default=200
        Total number of paired joint scenarios to generate.
    random_state : int, default=42
        Random seed for reproducibility.

    Returns
    -------
    List[Dict[str, Any]]
        List of scenario dictionaries containing:
        - scenario_id: int (1 to n_scenarios)
        - computer: str (shared hostname, e.g. "PC-0007")
        - host_event: dict (Host telemetry event)
        - iam_event: dict (IAM telemetry event with target_computer == computer)
        - scenario_type: str ("BOTH_BENIGN", "HOST_ATTACK_ONLY", "IAM_ATTACK_ONLY", "BOTH_ATTACK")
    """
    rng = np.random.default_rng(random_state)

    # 1. Distribute scenario types roughly evenly across n_scenarios
    base_counts = n_scenarios // len(SCENARIO_TYPES)
    remainder = n_scenarios % len(SCENARIO_TYPES)
    type_assignments = SCENARIO_TYPES * base_counts + SCENARIO_TYPES[:remainder]
    rng.shuffle(type_assignments)

    # 2. Time progression simulation over 24 hours
    base_time = pd.Timestamp("2025-01-15 08:00:00")
    second_offsets = np.sort(rng.uniform(0, 86400, size=n_scenarios))

    scenarios: List[Dict[str, Any]] = []

    for i in range(n_scenarios):
        scenario_id = i + 1
        stype = type_assignments[i]

        # Shared computer entity selected from fixed pool of 20 machines
        shared_computer = str(rng.choice(SCENARIO_COMPUTERS))
        source_computer = str(rng.choice(SCENARIO_COMPUTERS))
        user = str(rng.choice(FAKE_USERS))

        # Correlated timestamps: Host and IAM events occur close in time (within +/- 30s)
        scenario_time = base_time + pd.to_timedelta(second_offsets[i], unit="s")
        host_timestamp = scenario_time.strftime("%Y-%m-%d %H:%M:%S")
        iam_delta_sec = float(rng.uniform(-30, 30))
        iam_timestamp = (scenario_time + pd.to_timedelta(iam_delta_sec, unit="s")).strftime(
            "%Y-%m-%d %H:%M:%S"
        )

        host_is_attack = stype in ("HOST_ATTACK_ONLY", "BOTH_ATTACK")
        iam_is_attack = stype in ("IAM_ATTACK_ONLY", "BOTH_ATTACK")

        host_ev = _generate_host_event(
            event_id=scenario_id,
            computer=shared_computer,
            user=user,
            timestamp=host_timestamp,
            is_attack=host_is_attack,
            rng=rng,
        )

        iam_ev = _generate_iam_event(
            event_id=scenario_id,
            target_computer=shared_computer,
            source_computer=source_computer,
            user=user,
            timestamp=iam_timestamp,
            is_attack=iam_is_attack,
            rng=rng,
        )

        scenarios.append(
            {
                "scenario_id": scenario_id,
                "computer": shared_computer,
                "host_event": host_ev,
                "iam_event": iam_ev,
                "scenario_type": stype,
            }
        )

    return scenarios


