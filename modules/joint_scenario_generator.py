"""Synthetic Joint Multi-Agent Scenario Generator.

[SYNTHETIC DATA SOURCE NOTICE]
==============================
WARNING: ALL DATA GENERATED BY THIS MODULE IS SYNTHETIC TEST HARNESS DATA.
This module constructs paired test scenarios combining synthetic Windows Host
endpoint telemetry and IAM authentication logs. It does NOT represent real
enterprise telemetry, EDR events, or production authentication logs.
This synthetic test harness exists specifically to exercise cross-agent entity
correlation, multi-source conflict resolution, and joint escalation logic
in downstream coordinator modules (e.g., Module 13b conflict resolver).

Paired scenarios link Host and IAM events via a shared endpoint entity:
- 'computer' in Host events matches 'target_computer' in IAM events.
- Scenarios cover all four combinations (BOTH_BENIGN, HOST_ATTACK_ONLY,
  IAM_ATTACK_ONLY, BOTH_ATTACK) drawn from a constrained pool of ~20 computers.
"""

